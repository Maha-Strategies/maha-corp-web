/* eslint-disable @typescript-eslint/no-require-imports -- Local browser verification. */
const assert = require('node:assert/strict')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const base = process.env.ASTROLOGY_LOCAL_URL || 'http://localhost:3138'
if (!/^http:\/\/(?:localhost|127\.0\.0\.1):\d+$/.test(base)) throw new Error('Local preview only')
;(async () => {
  const browser = await chromium.launch({ headless: true, channel: 'chrome' })
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } })
    const errors = [], calls = []
    page.on('pageerror', error => errors.push(error.message))
    await page.route('**/api/astrology/chat', async route => {
      calls.push(route.request().postDataJSON())
      await route.fulfill({ json: { answer: 'You described wanting to begin while protecting quality. Try one bounded writing session [1]. What happened?', sources: [{ number: 1, title: 'The Orbital Mind — Action & constraint', locator: 'Chapter XI, §2.1', url: '/astrology/orbital-mind#action-constraint' }] } })
    })
    await page.goto(`${base}/astrology/orbital-mind`, { waitUntil: 'networkidle', timeout: 120000 })
    await page.goto(`${base}/astrology`, { waitUntil: 'networkidle', timeout: 120000 })
    await page.getByRole('button', { name: 'Reading', exact: true }).click()
    await page.getByRole('button', { name: 'Orbital Mind', exact: true }).click()
    const checkIn = page.getByRole('region', { name: 'Orbital Mind check-in' })
    for (const title of ['Wanting to act, holding back', 'Big ambitions, little follow-through', 'Reliable routines, no room for change', 'A vivid vision, hard to put into words', 'Always producing, rarely replenished']) {
      await checkIn.getByRole('button', { name: new RegExp(title) }).click()
      await checkIn.getByRole('heading', { name: 'One small experiment' }).waitFor()
    }
    await checkIn.getByRole('button', { name: /Wanting to act, holding back/ }).click()
    await page.getByLabel('Your situation (optional)').fill('I want to write but keep editing before I begin.')
    await page.getByLabel('What happened? (optional)').fill('I wrote a paragraph in twenty minutes.')
    await page.getByRole('button', { name: 'Chart', exact: true }).click()
    await page.getByRole('button', { name: 'Reading', exact: true }).click()
    assert.equal(await page.getByLabel('Your situation (optional)').inputValue(), 'I want to write but keep editing before I begin.')
    await page.screenshot({ path: '/private/tmp/maha-orbital-desktop.png', fullPage: true })
    for (const width of [1440, 375]) {
      await page.setViewportSize({ width, height: 1000 })
      const size = await page.evaluate(() => ({ client: document.documentElement.clientWidth, scroll: document.documentElement.scrollWidth }))
      assert.ok(size.scroll <= size.client, JSON.stringify({ width, ...size }))
    }
    await page.screenshot({ path: '/private/tmp/maha-orbital-mobile.png', fullPage: true })
    await page.getByRole('button', { name: 'Explore this with AI' }).click()
    assert.equal(calls.length, 0)
    assert.equal(await page.getByLabel('Conversation lens').inputValue(), 'orbital')
    assert.equal(await page.getByLabel('Orbital lens', { exact: true }).inputValue(), 'action-constraint')
    assert.equal(await page.getByRole('checkbox').isChecked(), false)
    await page.getByRole('button', { name: 'Ask AI', exact: false }).filter({ hasText: '↗' }).click()
    await page.getByRole('log').getByText(/You described wanting to begin/).waitFor()
    assert.equal(calls.length, 1)
    assert.equal(calls[0].chart, null)
    assert.equal(calls[0].orbital.lensId, 'action-constraint')
    assert.match(calls[0].orbital.outcome, /paragraph/)
    await page.getByText('Sources referenced', { exact: true }).click()
    const source = page.getByRole('link', { name: /The Orbital Mind — Action/ })
    const guide = await browser.newPage()
    await guide.goto(new URL(await source.getAttribute('href'), base).href, { waitUntil: 'networkidle' })
    await guide.getByRole('heading', { name: 'Action & constraint' }).waitFor()
    assert.match(await guide.locator('#theory').innerText(), /ten untested predictions/)
    await guide.close()
    await page.getByRole('button', { name: 'Remove notes from chat' }).click()
    await page.getByLabel('Your question', { exact: true }).fill('What should I try next?')
    await page.getByRole('button', { name: 'Ask AI', exact: false }).filter({ hasText: '↗' }).click()
    await page.getByRole('log').getByText(/You described wanting to begin/).waitFor()
    assert.equal(calls[1].orbital.situation, '')
    assert.equal(calls[1].orbital.outcome, '')
    assert.deepEqual(calls[1].history, [])
    assert.deepEqual(errors, [])
    console.log(JSON.stringify({ paidRequests: 0, mockedRequests: calls.length, checks: 'five lenses, practical experiments, retained check-in, mobile layout, explicit sharing, chart opt-out, source guide, removal of notes' }))
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
